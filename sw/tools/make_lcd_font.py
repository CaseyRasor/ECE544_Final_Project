"""Convert the CP437 8x16 font ROM (.mem) used by the VGA peripheral into a C
table for the MBWB LCD driver.

Usage: python make_lcd_font.py <font_rom_cp437_8x16.mem> <MBWB_LCD_font.c>
"""
import sys

src, dst = sys.argv[1], sys.argv[2]
rows = []
with open(src, encoding="utf-8") as f:
    for line in f:
        line = line.split("//")[0].strip()
        if line:
            rows.append(int(line, 16))
if len(rows) != 4096:
    sys.exit(f"expected 4096 rows, got {len(rows)}")

out = []
out.append("/**")
out.append(" * @file    MBWB_LCD_font.c")
out.append(" * @brief   CP437 8x16 bitmap font for the MBWB LCD driver.")
out.append(" *")
out.append(" * @detail")
out.append(" * Generated by sw/tools/make_lcd_font.py from font_rom_cp437_8x16.mem")
out.append(" * (the same font used by the MBWB VGA text controller). Do not edit by hand.")
out.append(" *")
out.append(" * Layout: 256 glyphs x 16 rows. Byte [ch * 16 + y] is row y of glyph ch;")
out.append(" * bit 7 is the leftmost pixel.")
out.append(" */")
out.append("/* SPDX-License-Identifier: MIT */")
out.append("")
out.append('#include "MBWB_LCD.h"')
out.append("")
out.append("const u8 MBWB_LCD_Font8x16[256U * 16U] =")
out.append("{")
for ch in range(256):
    g = rows[ch * 16:(ch + 1) * 16]
    vals = ", ".join(f"0x{v:02X}" for v in g)
    comment = chr(ch) if 0x20 <= ch < 0x7F and ch != 0x5C else f"0x{ch:02X}"
    out.append(f"    {vals}, /* {comment} */")
out.append("};")
out.append("")
with open(dst, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(out))
print(f"wrote {dst}")
